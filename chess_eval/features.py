import abc
import pandas as pd
import chess

from chess_eval.config import *


###################### Feature Bundle ######################


class FeatureBundle(abc.ABC):
    """
    Abstract base class for chess feature extraction bundles.

    Attributes
    ----------
    name : str
        Human-readable name of the feature bundle.
    features : set
        Set of feature column names generated by this bundle.
    """

    name: str
    features: set

    @staticmethod
    @abc.abstractmethod
    def compute(board: chess.Board) -> Dict[str, float]:
        """
        Compute the feature dictionary for a given chess board.

        Parameters
        ----------
        board : chess.Board
            A chess.Board object representing the game state.

        Returns
        -------
        dict
            Mapping of feature names to computed values.
        """
        pass

    @classmethod
    def transform(cls, df: pd.DataFrame) -> pd.DataFrame:
        """
        Transform a DataFrame of FEN strings by computing this feature bundle.

        Parameters
        ----------
        df : pd.DataFrame
            Input DataFrame containing a column named `FEN`.

        Returns
        -------
        pd.DataFrame
            DataFrame with new features appended.
        """
        df = df.copy()
        df.drop(columns=list(cls.features), inplace=True, errors="ignore")
        results = [cls.compute(chess.Board(fen)) for fen in df[FEN].values]
        return pd.concat([df, pd.DataFrame(results, index=df.index)], axis=1)


######################## Piece Info ########################


class PieceInfo(FeatureBundle):
    """
    Feature bundle capturing information about pieces on the board.

    Attributes
    ----------
    name : str
        "Piece Information"
    features : set
        Set of piece-related features like counts, values, and central occupancy.
    """

    name = "Piece Information"
    features = {
        "White_Pieces", "Black_Pieces",
        "White_Piece_Value", "Black_Piece_Value",
        "White_Pawn", "Black_Pawn",
        "White_Knight", "Black_Knight",
        "White_Bishop", "Black_Bishop",
        "White_Rook", "Black_Rook",
        "White_Queen", "Black_Queen",
        "White_Central_Pieces", "Black_Central_Pieces",
    }

    @staticmethod
    def compute(board: chess.Board) -> Dict[str, float]:
        """
        Count pieces, total piece values, and central square occupancy for both colors.

        Parameters
        ----------
        board : chess.Board
            Current chess board state.

        Returns
        -------
        dict
            Feature values for each piece type and central control.
        """
        piece_map = board.piece_map()

        w_total = b_total = 0
        w_value = b_value = 0.0
        w_central = b_central = 0
        counts = {f"{c}_{t}": 0 for c in ("White", "Black")
                  for t in ("Pawn", "Knight", "Bishop", "Rook", "Queen")}

        for sq, pc in piece_map.items():
            color = pc.color
            ptype = pc.piece_type

            if color:
                w_total += 1
                w_value += PIECE_VALUES[ptype]
            else:
                b_total += 1
                b_value += PIECE_VALUES[ptype]

            if ptype != chess.KING:
                key = f"{'White' if color else 'Black'}_{chess.piece_name(ptype).capitalize()}"
                counts[key] += 1

            if sq in CENTRAL_SQUARES:
                if color:
                    w_central += 1
                else:
                    b_central += 1

        out = {
            "White_Pieces": w_total,
            "Black_Pieces": b_total,
            "White_Piece_Value": w_value,
            "Black_Piece_Value": b_value,
            "White_Central_Pieces": w_central,
            "Black_Central_Pieces": b_central,
        }
        out.update(counts)
        return out


###################### Pawn Structure ######################


class PawnStructure(FeatureBundle):
    """
    Feature bundle capturing pawn structure features.

    Attributes
    ----------
    name : str
        "Pawn Structure"
    features : set
        Features related to pawn islands, isolated, doubled, and passed pawns.
    """

    name = "Pawn Structure"
    features = {
        "Isolated_Pawns_White", "Isolated_Pawns_Black",
        "Doubled_Pawns_White", "Doubled_Pawns_Black",
        "Passed_Pawns_White", "Passed_Pawns_Black",
        "Pawn_Islands_White", "Pawn_Islands_Black"
    }

    @staticmethod
    def fen_to_file_counts(board: chess.Board) -> Tuple[List[int], List[int]]:
        """
        Count pawns per file for each color.

        Parameters
        ----------
        board : chess.Board
            Current board state.

        Returns
        -------
        tuple of list of int
            Counts of pawns per file for white and black.
        """
        w = [0] * 8
        b = [0] * 8
        for sq, p in board.piece_map().items():
            if p.piece_type == chess.PAWN:
                if p.color:
                    w[chess.square_file(sq)] += 1
                else:
                    b[chess.square_file(sq)] += 1
        return w, b

    @staticmethod
    def isolated(counts: List[int]) -> int:
        """
        Count isolated pawns in a file count array.

        Parameters
        ----------
        counts : list of int
            Number of pawns per file.

        Returns
        -------
        int
            Number of isolated pawns.
        """
        return sum(c for i, c in enumerate(counts) if c > 0 and
                   (counts[i - 1] if i > 0 else 0) == 0 and
                   (counts[i + 1] if i < 7 else 0) == 0)

    @staticmethod
    def doubled(counts: List[int]) -> int:
        """
        Count doubled pawns in a file count array.

        Parameters
        ----------
        counts : list of int
            Number of pawns per file.

        Returns
        -------
        int
            Number of doubled pawns.
        """
        return sum(c - 1 for c in counts if c > 1)

    @staticmethod
    def passed(own: List[int], opp: List[int]) -> int:
        """
        Count passed pawns for a color.

        Parameters
        ----------
        own : list of int
            File counts for the color.
        opp : list of int
            File counts for the opponent.

        Returns
        -------
        int
            Number of passed pawns.
        """
        total = 0
        for i, c in enumerate(own):
            if c == 0:
                continue
            front = [i]
            if i > 0:
                front.append(i - 1)
            if i < 7:
                front.append(i + 1)
            if all(opp[f] == 0 for f in front):
                total += c
        return total

    @staticmethod
    def pawn_islands(board: chess.Board, color: bool) -> int:
        """
        Count pawn islands for a given color.

        Parameters
        ----------
        board : chess.Board
            Current board state.
        color : bool
            chess.WHITE or chess.BLACK.

        Returns
        -------
        int
            Number of pawn islands.
        """
        files = sorted({chess.square_file(sq) for sq, p in board.piece_map().items() if
                        p.piece_type == chess.PAWN and p.color == color})
        if not files:
            return 0
        islands = 1
        for i in range(1, len(files)):
            if files[i] != files[i - 1] + 1:
                islands += 1
        return islands

    @classmethod
    def compute(cls, board: chess.Board) -> Dict[str, int]:
        """
        Compute pawn structure metrics for both colors.

        Parameters
        ----------
        board : chess.Board
            Current board state.

        Returns
        -------
        dict
            Pawn structure features.
        """
        w, b = cls.fen_to_file_counts(board)
        return {
            "Isolated_Pawns_White": cls.isolated(w),
            "Isolated_Pawns_Black": cls.isolated(b),
            "Doubled_Pawns_White": cls.doubled(w),
            "Doubled_Pawns_Black": cls.doubled(b),
            "Passed_Pawns_White": cls.passed(w, b),
            "Passed_Pawns_Black": cls.passed(b, w),
            "Pawn_Islands_White": cls.pawn_islands(board, chess.WHITE),
            "Pawn_Islands_Black": cls.pawn_islands(board, chess.BLACK)
        }


####################### King Safety ########################


class KingSafety(FeatureBundle):
    """
    Feature bundle capturing king safety features.

    Attributes
    ----------
    name : str
        "King Safety"
    features : set
        Features related to castling, pawn shields, checks, and attacked squares around the king.
    """

    name = "King Safety"
    features = {
        "King_Castled_White", "King_Castled_Black",
        "King_Pawns_White", "King_Pawns_Black",
        "Open_Files",
        "King_Distance_to_Last_Rank_White", "King_Distance_to_Last_Rank_Black",
        "King_Castling_Rights_White", "King_Castling_Rights_Black",
        "King_Front_Pawns_White", "King_Front_Pawns_Black",
        "King_In_Check_White", "King_In_Check_Black",
        "King_Attacked_Neighbours_White", "King_Attacked_Neighbours_Black"
    }

    @staticmethod
    def king_castled(board: chess.Board, color: bool) -> int:
        """
        Check if king has castled.

        Parameters
        ----------
        board : chess.Board
        color : bool
            chess.WHITE or chess.BLACK

        Returns
        -------
        int
            1 if castled, 0 otherwise.
        """
        k = board.king(color)
        if color == chess.WHITE:
            return int((k == chess.G1 and board.piece_at(chess.H1) == chess.Piece(chess.ROOK, chess.WHITE))
                       or (k == chess.C1 and board.piece_at(chess.A1) == chess.Piece(chess.ROOK, chess.WHITE)))
        return int((k == chess.G8 and board.piece_at(chess.H8) == chess.Piece(chess.ROOK, chess.BLACK))
                   or (k == chess.C8 and board.piece_at(chess.A8) == chess.Piece(chess.ROOK, chess.BLACK)))

    @staticmethod
    def king_pawns(board: chess.Board, color: bool) -> int:
        """
        Count pawns surrounding the king.

        Parameters
        ----------
        board : chess.Board
        color : bool

        Returns
        -------
        int
            Number of pawns around the king.
        """
        sq = board.king(color)
        sf, sr = chess.square_file(sq), chess.square_rank(sq)
        cnt = 0
        for df in (-1, 0, 1):
            for dr in (-1, 0, 1):
                if df == 0 and dr == 0:
                    continue
                f, r = sf + df, sr + dr
                if 0 <= f <= 7 and 0 <= r <= 7:
                    p = board.piece_at(chess.square(f, r))
                    if p and p.piece_type == chess.PAWN and p.color == color:
                        cnt += 1
        return cnt

    @staticmethod
    def open_files(board: chess.Board) -> int:
        """
        Count the number of files with no pawns or semi-open files.

        Parameters
        ----------
        board : chess.Board

        Returns
        -------
        int
            Count of open files.
        """
        return sum(1 for f in range(8)
                   if not any(board.piece_at(chess.square(f, r)) == chess.Piece(chess.PAWN, chess.WHITE) for r in range(8))
                   or not any(board.piece_at(chess.square(f, r)) == chess.Piece(chess.PAWN, chess.BLACK) for r in range(8)))

    @staticmethod
    def king_distance(board: chess.Board, color: bool) -> int:
        """
        Distance from the king to its last rank.

        Parameters
        ----------
        board : chess.Board
        color : bool

        Returns
        -------
        int
            Rank distance to last row.
        """
        sq = board.king(color)
        r = chess.square_rank(sq)
        return (7 - r) if color == chess.WHITE else r

    @staticmethod
    def king_castling_rights(board: chess.Board, color: bool) -> int:
        """
        Whether the king has castling rights.

        Parameters
        ----------
        board : chess.Board
        color : bool

        Returns
        -------
        int
            1 if has castling rights, 0 otherwise.
        """
        return int(board.has_kingside_castling_rights(color) or board.has_queenside_castling_rights(color))

    @staticmethod
    def king_front_pawns(board: chess.Board, color: bool) -> int:
        """
        Count pawns directly in front of the king.

        Parameters
        ----------
        board : chess.Board
        color : bool

        Returns
        -------
        int
            Number of pawns in front.
        """
        sq = board.king(color)
        sf, sr = chess.square_file(sq), chess.square_rank(sq)
        dr = 1 if color == chess.WHITE else -1
        cnt = 0
        for df in (-1, 0, 1):
            f = sf + df
            r = sr + dr
            if 0 <= f <= 7 and 0 <= r <= 7:
                p = board.piece_at(chess.square(f, r))
                if p and p.piece_type == chess.PAWN and p.color == color:
                    cnt += 1
        return cnt

    @staticmethod
    def king_in_check(board: chess.Board, color: bool) -> int:
        """
        Whether the king is in check.

        Parameters
        ----------
        board : chess.Board
        color : bool

        Returns
        -------
        int
            1 if in check, 0 otherwise.
        """
        return int(board.is_check() and board.turn == color)

    @staticmethod
    def king_attacked_neighbours(board: chess.Board, color: bool) -> int:
        """
        Count the squares around the king attacked by the opponent.

        Parameters
        ----------
        board : chess.Board
        color : bool

        Returns
        -------
        int
            Number of attacked neighbouring squares.
        """
        sq = board.king(color)
        sf, sr = chess.square_file(sq), chess.square_rank(sq)
        enemy = not color
        cnt = 0
        for df in (-1, 0, 1):
            for dr in (-1, 0, 1):
                if df == 0 and dr == 0:
                    continue
                f, r = sf + df, sr + dr
                if 0 <= f <= 7 and 0 <= r <= 7 and board.is_attacked_by(enemy, chess.square(f, r)):
                    cnt += 1
        return cnt

    @classmethod
    def compute(cls, board: chess.Board) -> Dict[str, int]:
        """
        Compute king safety features for both colors.

        Parameters
        ----------
        board : chess.Board

        Returns
        -------
        dict
            King safety feature values.
        """
        return {
            "King_Castled_White": cls.king_castled(board, chess.WHITE),
            "King_Castled_Black": cls.king_castled(board, chess.BLACK),
            "King_Pawns_White": cls.king_pawns(board, chess.WHITE),
            "King_Pawns_Black": cls.king_pawns(board, chess.BLACK),
            "Open_Files": cls.open_files(board),
            "King_Distance_to_Last_Rank_White": cls.king_distance(board, chess.WHITE),
            "King_Distance_to_Last_Rank_Black": cls.king_distance(board, chess.BLACK),
            "King_Castling_Rights_White": cls.king_castling_rights(board, chess.WHITE),
            "King_Castling_Rights_Black": cls.king_castling_rights(board, chess.BLACK),
            "King_Front_Pawns_White": cls.king_front_pawns(board, chess.WHITE),
            "King_Front_Pawns_Black": cls.king_front_pawns(board, chess.BLACK),
            "King_In_Check_White": cls.king_in_check(board, chess.WHITE),
            "King_In_Check_Black": cls.king_in_check(board, chess.BLACK),
            "King_Attacked_Neighbours_White": cls.king_attacked_neighbours(board, chess.WHITE),
            "King_Attacked_Neighbours_Black": cls.king_attacked_neighbours(board, chess.BLACK),
        }
######################### Mobility #########################


class Mobility(FeatureBundle):
    """
    Feature bundle capturing piece mobility (legal moves) for all piece types.

    Attributes
    ----------
    name : str
        "Piece Mobility"
    features : set
        Mobility features for each piece type and color.
    """

    name = "Piece Mobility"
    features = {
        "Mobility_King_White", "Mobility_Queen_White", "Mobility_Rook_White",
        "Mobility_Bishop_White", "Mobility_Knight_White", "Mobility_Pawn_White",
        "Mobility_King_Black", "Mobility_Queen_Black", "Mobility_Rook_Black",
        "Mobility_Bishop_Black", "Mobility_Knight_Black", "Mobility_Pawn_Black"
    }

    @staticmethod
    def compute(board: chess.Board) -> Dict[str, int]:
        """
        Count legal moves for each piece type and color.

        Parameters
        ----------
        board : chess.Board

        Returns
        -------
        dict
            Mobility counts for all pieces.
        """
        move_map = {sq: 0 for sq in chess.SQUARES}
        for mv in board.legal_moves:
            move_map[mv.from_square] += 1

        out: Dict[str, int] = {}
        pieces = [
            (chess.KING, "King"),
            (chess.QUEEN, "Queen"),
            (chess.ROOK, "Rook"),
            (chess.BISHOP, "Bishop"),
            (chess.KNIGHT, "Knight"),
            (chess.PAWN, "Pawn")
        ]

        for color, cname in [(chess.WHITE, "White"), (chess.BLACK, "Black")]:
            for ptype, pname in pieces:
                count = sum(move_map[sq] for sq in board.pieces(ptype, color))
                out[f"Mobility_{pname}_{cname}"] = count

        return out


########################## Attack ##########################


class Attack(FeatureBundle):
    """
    Feature bundle capturing threats, hanging and undefended pieces.

    Attributes
    ----------
    name : str
        "Relations"
    features : set
        Features capturing threats, hanging pieces, and undefended pieces and points.
    """

    name = "Relations"
    features = {
        "Threats_Created_White", "Threats_Created_Black",
        "Hanging_Pieces_White", "Hanging_Pieces_Black",
        "Hanging_Points_White", "Hanging_Points_Black",
        "Undefended_Pieces_White", "Undefended_Pieces_Black",
        "Undefended_Points_White", "Undefended_Points_Black"
    }

    @staticmethod
    def compute(board: chess.Board) -> Dict[str, int]:
        """
        Compute threats, hanging pieces, and undefended pieces for both colors.

        Parameters
        ----------
        board : chess.Board

        Returns
        -------
        dict
            Attack-related features for both colors.
        """
        out: Dict[str, int] = {}

        for color, cname in [(chess.WHITE, "White"), (chess.BLACK, "Black")]:
            enemy = not color

            # Threats
            threats = sum(
                1 for ptype in (chess.PAWN, chess.KNIGHT, chess.BISHOP, chess.ROOK, chess.QUEEN)
                for sq in board.pieces(ptype, enemy)
                if board.is_attacked_by(color, sq)
            )
            out[f"Threats_Created_{cname}"] = threats

            h_count = h_pts = u_count = u_pts = 0

            for ptype in (chess.PAWN, chess.KNIGHT, chess.BISHOP, chess.ROOK, chess.QUEEN):
                for sq in board.pieces(ptype, color):
                    defended = board.is_attacked_by(color, sq)
                    attacked = board.is_attacked_by(enemy, sq)

                    if attacked and not defended:
                        h_count += 1
                        h_pts += PIECE_VALUES[ptype]

                    if not defended:
                        u_count += 1
                        u_pts += PIECE_VALUES[ptype]

            out[f"Hanging_Pieces_{cname}"] = h_count
            out[f"Hanging_Points_{cname}"] = h_pts
            out[f"Undefended_Pieces_{cname}"] = u_count
            out[f"Undefended_Points_{cname}"] = u_pts

        return out


###################### Board Control #######################


class BoardControl(FeatureBundle):
    """
    Feature bundle capturing board control metrics including central control, open columns,
    alignments, protected advanced pawns, and total controlled squares.

    Attributes
    ----------
    name : str
        "Board Control"
    features : set
        Board control features for both colors.
    """

    name = "Board Control"
    features = {
        "Central_Squares_Control_White", "Central_Squares_Control_Black",
        "Open_Columns_White", "Open_Columns_Black",
        "SemiOpen_Columns_White", "SemiOpen_Columns_Black",
        "Rook_on_Open_Column_White", "Rook_on_Open_Column_Black",
        "Protected_Advanced_Pawn_White", "Protected_Advanced_Pawn_Black",
        "Rook_Queen_Aligned_White", "Rook_Queen_Aligned_Black",
        "Rooks_Aligned_White", "Rooks_Aligned_Black",
        "Controlled_Squares_White", "Controlled_Squares_Black"
    }

    central = [chess.D4, chess.D5, chess.E4, chess.E5]

    @staticmethod
    def _open_columns(board: chess.Board) -> List[Tuple[bool, bool]]:
        """
        Check which columns are open or semi-open for both colors.

        Parameters
        ----------
        board : chess.Board

        Returns
        -------
        list of tuple
            Each tuple is (has_white_pawn, has_black_pawn) per column.
        """
        cols: List[Tuple[bool, bool]] = []
        for f in range(8):
            has_w = any(board.piece_at(chess.square(f, r)) == chess.Piece(chess.PAWN, chess.WHITE) for r in range(8))
            has_b = any(board.piece_at(chess.square(f, r)) == chess.Piece(chess.PAWN, chess.BLACK) for r in range(8))
            cols.append((has_w, has_b))
        return cols

    @staticmethod
    def _aligned(board: chess.Board, color: bool) -> Tuple[int, int]:
        """
        Check rook-queen and rook-rook alignments.

        Parameters
        ----------
        board : chess.Board
        color : bool

        Returns
        -------
        tuple of int
            (rook_queen_aligned, rooks_aligned)
        """
        rooks = list(board.pieces(chess.ROOK, color))
        queens = list(board.pieces(chess.QUEEN, color))
        rq = rr = 0

        for r in rooks:
            rf, rrk = chess.square_file(r), chess.square_rank(r)
            for q in queens:
                if rf == chess.square_file(q) or rrk == chess.square_rank(q):
                    rq = 1

        for i in range(len(rooks)):
            r1, f1, r1r = rooks[i], chess.square_file(rooks[i]), chess.square_rank(rooks[i])
            for j in range(i + 1, len(rooks)):
                r2 = rooks[j]
                if f1 == chess.square_file(r2) or r1r == chess.square_rank(r2):
                    rr = 1

        return rq, rr

    @staticmethod
    def _protected_advanced_pawn(board: chess.Board, color: bool) -> int:
        """
        Check if there is a protected advanced pawn.

        Parameters
        ----------
        board : chess.Board
        color : bool

        Returns
        -------
        int
            1 if exists, 0 otherwise.
        """
        ranks = range(3, 6) if color == chess.WHITE else range(2, 5)
        for r in ranks:
            for f in range(8):
                sq = chess.square(f, r)
                piece = board.piece_at(sq)
                if piece and piece.color == color and piece.piece_type == chess.PAWN:
                    if any(board.is_attacked_by(color, sq2)
                           for sq2 in board.pieces(chess.KNIGHT, color)
                           | board.pieces(chess.BISHOP, color)
                           | board.pieces(chess.ROOK, color)
                           | board.pieces(chess.QUEEN, color)):
                        return 1
        return 0

    @staticmethod
    def compute(board: chess.Board) -> Dict[str, int]:
        """
        Compute board control features for both colors.

        Parameters
        ----------
        board : chess.Board

        Returns
        -------
        dict
            Board control feature values.
        """
        cols = BoardControl._open_columns(board)
        out: Dict[str, int] = {}

        for color, cname in [(chess.WHITE, "White"), (chess.BLACK, "Black")]:
            out[f"Central_Squares_Control_{cname}"] = sum(1 for sq in BoardControl.central if board.is_attacked_by(color, sq))
            open_c = semi_c = 0
            for f, (has_w, has_b) in enumerate(cols):
                if not has_w and not has_b:
                    open_c += 1
                else:
                    if color == chess.WHITE and not has_w:
                        semi_c += 1
                    elif color == chess.BLACK and not has_b:
                        semi_c += 1
            out[f"Open_Columns_{cname}"] = open_c
            out[f"SemiOpen_Columns_{cname}"] = semi_c

            rook_flag = 0
            for sq in board.pieces(chess.ROOK, color):
                f = chess.square_file(sq)
                has_w, has_b = cols[f]
                if not has_w and not has_b:
                    rook_flag = 1
                    break
            out[f"Rook_on_Open_Column_{cname}"] = rook_flag

            out[f"Protected_Advanced_Pawn_{cname}"] = BoardControl._protected_advanced_pawn(board, color)
            rq, rr = BoardControl._aligned(board, color)
            out[f"Rook_Queen_Aligned_{cname}"] = rq
            out[f"Rooks_Aligned_{cname}"] = rr

            out[f"Controlled_Squares_{cname}"] = sum(1 for sq in chess.SQUARES if board.is_attacked_by(color, sq))

        return out


######################## Game Info #########################


class GameInfo(FeatureBundle):
    """
    Feature bundle capturing game state info like move counts, phase, turn, and en passant.

    Attributes
    ----------
    name : str
        "Game Info"
    features : set
        Game info features.
    """

    name = "Game Info"
    features = {"Halfmove_Clock", "Fullmove_Number", "Phase", "Side_To_Move_White", "Has_En_Passant"}

    @staticmethod
    def phase(board: chess.Board) -> float:
        """
        Compute game phase based on remaining material.

        Parameters
        ----------
        board : chess.Board

        Returns
        -------
        float
            Phase ratio (0=opening, 1=initial total material).
        """
        total = sum(PIECE_VALUES[pc.piece_type] for pc in board.piece_map().values())
        initial = 16*1 + 4*3 + 4*3 + 4*5 + 2*9  # total material
        return total / initial

    @classmethod
    def compute(cls, board: chess.Board) -> Dict[str, float]:
        """
        Compute game state features.

        Parameters
        ----------
        board : chess.Board

        Returns
        -------
        dict
            Game info features.
        """
        return {
            "Halfmove_Clock": board.halfmove_clock,
            "Fullmove_Number": board.fullmove_number,
            "Phase": cls.phase(board),
            "Side_To_Move_White": int(board.turn),
            "Has_En_Passant": int(board.ep_square is not None)
        }


